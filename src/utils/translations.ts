export type TranslationKey = keyof typeof TRANSLATIONS.en;

export function t(lang: AppLanguage | string = 'en', key: TranslationKey | string): string {
  const safeLang = (lang === 'am' ? 'am' : 'en') as 'en' | 'am';
  const dict = TRANSLATIONS[safeLang] as Record<string, string>;
  const fallbackDict = TRANSLATIONS.en as Record<string, string>;
  return dict[key] || fallbackDict[key] || String(key);
}
